#!/usr/bin/env python3
"""Records every word the watch says with the Mac's own voice and packs them into ring_pet/clips.h
as 8 kHz, 8-bit sound (about 300 KB of the C3's 4 MB flash).

  python3 gen_clips.py            (uses Daniel, the UK English voice)
  python3 gen_clips.py Samantha   (any voice from `say -v '?'`)
"""
import os, subprocess, sys, tempfile, wave, array, math

HERE = os.path.dirname(os.path.abspath(__file__))
VOICE = sys.argv[1] if len(sys.argv) > 1 else "Daniel"
LOUD = os.environ.get("CLIP_LOUD") == "1"  # for no amp: speaker straight off GPIO20/21
RATE = int(os.environ.get("CLIP_RATE", "8000"))  # 22050 for FM-like quality (needs the Huge APP partition)

ONES = ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten", "eleven", "twelve",
        "thirteen", "fourteen", "fifteen", "sixteen", "seventeen", "eighteen", "nineteen"]
TENS = ["twenty", "thirty", "forty", "fifty"]
DAYS = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"]
MONTHS = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October",
          "November", "December"]
ORD = ["first", "second", "third", "fourth", "fifth", "sixth", "seventh", "eighth", "ninth", "tenth", "eleventh",
       "twelfth", "thirteenth", "fourteenth", "fifteenth", "sixteenth", "seventeenth", "eighteenth", "nineteenth",
       "twentieth", "thirtieth"]
WORDS = ["it's", "oh", "o'clock", "AM", "PM", "the", "time", "date", "timer", "alarm", "stopwatch", "minutes",
         "minute", "seconds", "hours", "set for", "started", "stopped", "cancelled", "on", "off", "done", "time's up",
         "wake up", "no Wi-Fi", "time updated", "hello", "goodbye", "choose", "turn to set", "click to start",
         "and", "at"]
CLIPS = ONES + TENS + DAYS + MONTHS + ORD + WORDS


def ident(w):
    return "W_" + "".join(c if c.isalnum() else "_" for c in w.upper()).strip("_")


def record(word):
    with tempfile.TemporaryDirectory() as d:
        out = os.path.join(d, "w.wav")
        subprocess.run(["say", "-v", VOICE, "-r", "190", "-o", out, f"--data-format=LEI16@{RATE}", word], check=True)
        with wave.open(out) as w:
            s = array.array("h", w.readframes(w.getnframes()))
    # trim the silence either side, then normalise loud (the PAM does the rest)
    keep = [i for i, v in enumerate(s) if abs(v) > 300]
    if keep: s = s[max(0, keep[0] - 80): keep[-1] + 160]
    peak = max(1, max(abs(v) for v in s))
    if LOUD:  # squash the quiet parts up so speech straight off the pins is as loud as the beeps
        return bytes(int(127.5 + 127 * math.tanh(6 * v / peak) / math.tanh(6)) for v in s)
    gain = 32000 / peak
    return bytes(max(0, min(255, int(v * gain / 256) + 128)) for v in s)


def main():
    out = os.environ.get("CLIPS_OUT") or os.path.join(HERE, "ring_pet", "clips.h")
    total = 0
    lines = ["// Generated by gen_clips.py: every word the watch can say, " + str(RATE) + " Hz unsigned 8-bit. Don't edit by hand.",
             "#pragma once", "#include <stdint.h>", f"#define CLIP_RATE {RATE}", ""]
    table = []
    for w in CLIPS:
        data = record(w); total += len(data)
        name = ident(w)
        lines.append(f"static const uint8_t {name}_DATA[{len(data)}] = {{" + ",".join(map(str, data)) + "};")
        table.append((name, len(data)))
    lines.append("")
    lines.append("struct Clip { const uint8_t *data; uint32_t len; };")
    lines.append("enum ClipId {" + ", ".join(n for n, _ in table) + ", CLIP_COUNT};")
    lines.append("static const Clip CLIPS[CLIP_COUNT] = {" + ", ".join(f"{{{n}_DATA, {l}}}" for n, l in table) + "};")
    open(out, "w").write("\n".join(lines) + "\n")
    print(f"{len(CLIPS)} clips, {total / 1024:.0f} KB of sound -> {out}")


if __name__ == "__main__":
    main()
