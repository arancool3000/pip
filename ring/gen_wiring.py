#!/usr/bin/env python3
"""Records the spoken wiring guide (hold BOOT 3 s) into ring_pet/wiring.h with the Mac's voice."""
import array, math, os, subprocess, tempfile, wave
HERE = os.path.dirname(os.path.abspath(__file__))
TEXT = ("Wiring. The LED ring. Use the IN side only, leave OUT empty. "
        "V goes to five V. G goes to ground. S goes straight to G P I O ten. Connect V and G first, then S. "
        "The clicky wheel. Plus goes to three V three. Not five volts. "
        "G N D goes to ground. C L K goes to G P I O three. D T goes to G P I O four. "
        "S W goes to G P I O five. The speaker stays on twenty and twenty one.")
RATE = 16000
with tempfile.TemporaryDirectory() as d:
    out = os.path.join(d, "w.wav")
    subprocess.run(["say", "-v", "Daniel", "-r", "170", "-o", out, f"--data-format=LEI16@{RATE}", TEXT], check=True)
    w = wave.open(out); s = [v / 32768 for v in array.array("h", w.readframes(w.getnframes()))]
peak = max(abs(v) for v in s)
data = bytes(int(127.5 + 127 * math.tanh(6 * v / peak) / math.tanh(6)) for v in s)  # loud enough with no amp
open(os.path.join(HERE, "ring_pet", "wiring.h"), "w").write(
    "// Generated by gen_wiring.py: the spoken wiring, %d Hz unsigned 8-bit.\n#pragma once\n#include <stdint.h>\n"
    "#define WIRING_RATE %d\nstatic const uint8_t WIRING[%d] = {%s};\n" % (RATE, RATE, len(data), ",".join(map(str, data))))
print("wrote ring_pet/wiring.h")
